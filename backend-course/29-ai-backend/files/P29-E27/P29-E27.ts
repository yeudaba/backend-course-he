//
// לפני ששולחים פנייה של לקוח למודל (או ללוג), מחליפים פרטים אישיים בתגיות:
//   - אימייל ← [EMAIL]   (כולל + ונקודות לפני ה־@, ודומיין עם כמה חלקים: shop.co.il)
//   - מספר כרטיס אשראי: 13 עד 16 ספרות, אפשר עם רווח או מקף בין ספרות ← [CARD]
//   - טלפון נייד ישראלי: 05X-XXX-XXXX, עם או בלי מקפים/רווחים, או עם +972 במקום ה־0 ← [PHONE]
// כל השאר — כמו שהוא. מספרים קצרים יותר (מספר הזמנה של 12 ספרות, ת"ז של 9) לא מוחלפים.

const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;
const CARD = /\b(?:\d[ -]?){12,15}\d\b/g;
const PHONE = /(?:\+972[- ]?|\b0)5\d[- ]?\d{3}[- ]?\d{4}\b/g;

export function redactPII(text: string): string {
  return text.replace(EMAIL, "[EMAIL]").replace(CARD, "[CARD]").replace(PHONE, "[PHONE]");
}
