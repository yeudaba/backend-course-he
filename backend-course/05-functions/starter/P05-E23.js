// P05-E23: קבוצת גיל. הקלטים והפלט הרצוי:
// ""    → "שגיאה: חובה להזין גיל"         "   " → "שגיאה: חובה להזין גיל"
// "abc" → "שגיאה: גיל חייב להיות מספר"
// "-5"  → "שגיאה: גיל לא הגיוני"          "200" → "שגיאה: גיל לא הגיוני"
// "0"   → "קבוצה: קטין"                    "10"  → "קבוצה: קטין"
// "30"  → "קבוצה: מבוגר"                   "70"  → "קבוצה: גמלאי"
// ageGroup("5", 6) → "שגיאה: גיל לא הגיוני" (minAge: הגיל המינימלי המותר)
function ageGroup(input, minAge = 1) {
  const age = Number(input);
  if (!age) {
    return "שגיאה: חובה להזין גיל";
  }
  if (Number.isNaN(age)) {
    return "שגיאה: גיל חייב להיות מספר";
  }
  if (age < minAge || age > 120) {
    return "שגיאה: גיל לא הגיוני";
  }
  if (age < 18) {
    return "קבוצה: קטין";
  }
  if (age < 65) {
    return "קבוצה: מבוגר";
  }
  return "קבוצה: גמלאי";
}

console.log(ageGroup("30"));

module.exports = { ageGroup };
