import { test } from "node:test";
import { run, sameOutput } from "./_out.mjs";

const FILE = "P02-E14.js";

test("487 ש״ח, טיפ 12%, שישה סועדים", () => {
  sameOutput(run(import.meta.url, FILE), ["חשבון: 487", "טיפ (12%): 58.44", "סה״כ עם טיפ: 545.44", "כל אחד משלם: 91", "נאסף בפועל: 546", "עודף לטיפ: 0.56"]);
});

test("300 ש״ח, טיפ 15%, שבעה סועדים", () => {
  const r = run(import.meta.url, FILE, {
    changes: [
      [/=\s*487\b/, "= 300", "את החשבון (= 487)"],
      [/=\s*12\s*;/, "= 15;", "את אחוז הטיפ במשתנה (= 12;)"],
      [/=\s*6\s*;/, "= 7;", "את מספר הסועדים במשתנה (= 6;)"],
    ],
  });
  sameOutput(r, ["חשבון: 300", "טיפ (15%): 45.00", "סה״כ עם טיפ: 345.00", "כל אחד משלם: 50", "נאסף בפועל: 350", "עודף לטיפ: 5.00"]);
});
