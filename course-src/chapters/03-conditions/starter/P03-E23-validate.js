// P03-E23: בדיקת קלט של גיל. נסה את הקלטים: "", "   ", "abc", "-5", "200", "10", "30", "70"
// הפלט הרצוי לכל אחד:
// ""    → שגיאה: חובה להזין גיל
// "   " → שגיאה: חובה להזין גיל
// "abc" → שגיאה: גיל חייב להיות מספר
// "-5"  → שגיאה: גיל לא הגיוני
// "200" → שגיאה: גיל לא הגיוני
// "10"  → קבוצה: קטין
// "30"  → קבוצה: מבוגר
// "70"  → קבוצה: גמלאי
const ageInput = "   ";
const age = Number(ageInput);

if (age < 0 || age > 120) {
  console.log("שגיאה: גיל לא הגיוני");
} else if (ageInput === "") {
  console.log("שגיאה: חובה להזין גיל");
} else if (Number.isNaN(age)) {
  console.log("שגיאה: גיל חייב להיות מספר");
} else if (age < 65) {
  console.log("קבוצה: מבוגר");
} else if (age < 18) {
  console.log("קבוצה: קטין");
} else {
  console.log("קבוצה: גמלאי");
}
